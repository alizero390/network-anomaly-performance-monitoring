"""Explain the alarms raised on the real February test windows (D23, part 1).

Usage (repository root, virtual environment active, raw data available):

    python scripts/attribute_test_alarms.py

Descriptive only: nothing is calibrated or chosen, and the monitoring results are not
changed. Every one of the 87 test windows (5,000 records, time order) is described with
all labels: attacks, recall, FPR, calibrated F1 and the attack-category mix. Windows
whose calibrated F1 is at least 0.05 below the frozen reference are flagged and given a
cause with the Paper 1 rules (nadmon.window_attribution). Then every alarm in
results/strategies/test/natural_test.csv is matched to its window.

Predictions: results/strategies/test/test_predictions.csv from the test run (local, not
committed); if it is missing, the saved model predicts again.

Outputs in results/test_alarm_attribution/ (all small, commit them):
    windows.csv     one row per window
    categories.csv  one row per window and attack category
    alarms.csv      every natural-test alarm with its window's description
    dip_mix.csv     category mix and recall in the flagged windows against the others
    summary.md      readable summary
"""

from __future__ import annotations

import json

import joblib
import numpy as np
import pandas as pd

from nadmon import february, frozen
from nadmon import window_attribution as wa
from nadmon.config import PROJECT_DIR, load_paths

RESULTS = PROJECT_DIR / "results"
CONFIG = PROJECT_DIR / "configs" / "strategies.toml"
TEST = RESULTS / "strategies" / "test"
FLOOR_NATURAL = RESULTS / "strategy_a_floor" / "test" / "natural.csv"
OUT = RESULTS / "test_alarm_attribution"
SHOW = range(40, 61)  # windows printed in full


def reference_fpr() -> float:
    """Pooled validation FPR from the committed window metrics."""
    v = pd.read_csv(RESULTS / "validation_window_metrics.csv")
    return float(v["FP"].sum() / (v["FP"].sum() + v["TN"].sum()))


def test_predictions(paths, y: np.ndarray, X: pd.DataFrame) -> tuple[np.ndarray, str]:
    path = TEST / "test_predictions.csv"
    if path.is_file():
        pred = pd.read_csv(path)
        if len(pred) == len(y) and (pred["TrueLabel"].to_numpy() == y).all():
            return pred["Prediction"].to_numpy(dtype=int), "test_predictions.csv"
        print("   test_predictions.csv does not line up with the raw data; predicting again.")
    model = joblib.load(paths.models_dir / "random_forest_baseline.joblib")
    return model.predict(X).astype(int), "saved model"


def alarm_rows(windows: pd.DataFrame) -> pd.DataFrame:
    """Every alarm of the test runs, joined to its window.

    natural_test.csv gives the last data window of the alarming cohort. The D22 file
    gives the window at which the alarm was raised (release time), so only its Strategy A
    warnings are used here.
    """
    rows = []
    nat = pd.read_csv(TEST / "natural_test.csv")
    for r in nat.itertuples(index=False):
        for w in str(r.alarm_windows).split():
            if w != "nan":
                rows.append(
                    {
                        "source": "D14 test run",
                        "strategy": r.strategy,
                        "condition": r.condition,
                        "window": int(w),
                    }
                )
    if FLOOR_NATURAL.is_file():
        fl = pd.read_csv(FLOOR_NATURAL)
        for r in fl[fl["strategy"] == "A_floor"].itertuples(index=False):
            for w in str(r.alarm_windows).split():
                if w != "nan":
                    rows.append(
                        {
                            "source": "D22 test run",
                            "strategy": r.strategy,
                            "condition": r.condition,
                            "window": int(w),
                        }
                    )
    alarms = pd.DataFrame(rows)
    cols = [
        "window",
        "attacks",
        "recall",
        "fpr",
        "f1_calibrated",
        "flagged",
        "cause",
        "top_missed_category",
    ]
    return alarms.merge(windows[cols], on="window", how="left")


def fmt(x, digits=3):
    return "" if pd.isna(x) else f"{x:.{digits}f}"


def write_summary(windows, alarms, mix, ref, source) -> str:
    flagged = windows[windows["flagged"]]
    lines = [
        "# Attribution of the real test-window alarms (D23, part 1)",
        "",
        "Generated by `scripts/attribute_test_alarms.py`. All labels used (the truth, not "
        "what a monitor saw). Predictions from " + source + ".",
        "",
        f"Reference: calibrated F1 {ref.f1_calibrated:.4f}, recall {ref.recall:.4f}, "
        f"FPR {ref.fpr:.4f} (validation), attack share pi0 {ref.pi0:.4f}. A window is "
        f"flagged at a drop of at least {ref.drop}; n_min {ref.n_min}; false-positive "
        f"burst above {ref.fp_burst:.4f}.",
        "",
        f"## Flagged windows: {len(flagged)} of {len(windows)}",
        "",
        "| Window | Attacks | Recall | FPR | Cal. F1 | Cause "
        "| Most missed category (share of misses) |",
        "|---:|---:|---:|---:|---:|---|---|",
    ]
    for r in flagged.itertuples(index=False):
        lines.append(
            f"| {r.window} | {r.attacks} | {fmt(r.recall)} | {fmt(r.fpr, 4)} | "
            f"{fmt(r.f1_calibrated)} | {r.cause} | {r.top_missed_category or ''} "
            f"({fmt(r.top_missed_share_of_misses, 2)}) |"
        )
    lines += [
        "",
        "Causes: " + ", ".join(f"{k} {v}" for k, v in flagged["cause"].value_counts().items()),
        "",
    ]
    lines += [
        "## Alarms matched to windows",
        "",
        "| Strategy | Condition | Window | Flagged | Cause |",
        "|---|---|---:|---|---|",
    ]
    for r in alarms.itertuples(index=False):
        lines.append(f"| {r.strategy} | {r.condition} | {r.window} | {r.flagged} | {r.cause} |")
    lines += [
        "",
        "## Attack-category mix: flagged windows against all other windows",
        "",
        "| Category | Share (flagged) | Share (others) | Recall (flagged) | Recall (others) "
        "| Missed (flagged) | Missed at others' recall |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for r in mix.itertuples(index=False):
        lines.append(
            f"| {r.category} | {fmt(r.share_dip)} | {fmt(r.share_baseline)} | "
            f"{fmt(r.recall_dip)} | {fmt(r.recall_baseline)} | {int(r.missed_dip)} | "
            f"{fmt(r.missed_expected_at_baseline_recall, 0)} |"
        )
    lines += [
        "",
        "If the flagged windows miss many more records than 'missed at others' recall', "
        "recall fell within categories; if the two are close, the dip comes from the mix.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    cfg = frozen.read_config(CONFIG)
    cal = frozen.calibration_from_config(cfg)
    settings = frozen.settings_from_config(cfg)
    ref = wa.References(
        pi0=cal.pi0,
        recall=cal.recall,
        fpr=reference_fpr(),
        f1_calibrated=cal.reference_f1_calibrated,
        n_min=cal.n_min,
        drop=settings.drop,
    )
    OUT.mkdir(parents=True, exist_ok=True)
    paths = load_paths()
    print("1. Test partition ...")
    X, y, category = february.load_frames(paths, "test")
    pred, source = test_predictions(paths, y, X)
    february.partition(X, y, category, pred)  # same checks as the test run
    del X
    print(f"   {len(y):,} records; predictions from {source}")

    print("2. Windows ...")
    windows, cats = wa.window_table(y, pred, category, settings.window_size, ref)
    windows.to_csv(OUT / "windows.csv", index=False, lineterminator="\n")
    cats.to_csv(OUT / "categories.csv", index=False, lineterminator="\n")
    flagged = windows.loc[windows["flagged"], "window"].tolist()
    judged = windows.loc[windows["attacks"] >= ref.n_min, "window"]
    others = [w for w in judged if w not in flagged]
    mix = wa.category_shift(cats, flagged, others)
    mix.to_csv(OUT / "dip_mix.csv", index=False, lineterminator="\n")

    print("3. Alarms ...")
    alarms = alarm_rows(windows)
    alarms.to_csv(OUT / "alarms.csv", index=False, lineterminator="\n")
    (OUT / "summary.md").write_text(
        write_summary(windows, alarms, mix, ref, source), encoding="utf-8"
    )
    (OUT / "run.json").write_text(
        json.dumps(
            {
                "config_sha256": frozen.config_hash(CONFIG),
                "predictions": source,
                "references": ref.__dict__,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )

    pd.set_option("display.width", 200)
    cols = [
        "window",
        "attacks",
        "attack_share",
        "recall",
        "fpr",
        "f1_calibrated",
        "flagged",
        "cause",
        "top_missed_category",
        "top_missed_share_of_misses",
    ]
    print(f"\nWindows {SHOW.start}-{SHOW.stop - 1}:")
    print(windows[windows["window"].isin(SHOW)][cols].round(4).to_string(index=False))
    print(f"\nFlagged windows (all): {flagged}")
    print("\nCategory mix, flagged windows against the others:")
    print(
        mix[
            [
                "category",
                "share_dip",
                "share_baseline",
                "recall_dip",
                "recall_baseline",
                "missed_dip",
                "missed_expected_at_baseline_recall",
            ]
        ]
        .round(3)
        .to_string(index=False)
    )
    print(f"\nOutputs in {OUT}")


if __name__ == "__main__":
    main()
