"""Check which thesis scenarios can be built from the February validation partition.

Usage:  python scripts/check_scenarios.py

Needs results/validation_predictions.csv (scripts/baseline.py) and
results/validation_categories.csv with its Service column
(scripts/export_validation_categories.py, run after 2026-11-12). Uses no raw data and
never touches the test partition.

Writes results/scenarios/:
    feb_rf_validation_strata.csv     records, positive predictions and rate per stratum
    feb_rf_validation_scenarios.csv  intended vs computed ground truth (design spec D4)
    feb_rf_validation_labels.csv     cohorts after pooling, per label availability (D7, D8)
    README.md                        the two tables in readable form
"""

from __future__ import annotations

import pandas as pd

from nadmon import labels as lb
from nadmon import scenarios as sc
from nadmon.config import PROJECT_DIR

RESULTS = PROJECT_DIR / "results"
OUT = RESULTS / "scenarios"
WINDOW_SIZE = 5000
LABEL_SEED = 20261112


def main() -> None:
    pred = pd.read_csv(RESULTS / "validation_predictions.csv")
    cats_path = RESULTS / "validation_categories.csv"
    if not cats_path.is_file():
        raise SystemExit("Run scripts/export_validation_categories.py first.")
    cats = pd.read_csv(cats_path, keep_default_na=False)
    if "Service" not in cats.columns:
        raise SystemExit(
            "validation_categories.csv has no Service column: pull the latest code and run "
            "scripts/export_validation_categories.py again."
        )
    data = pred.merge(cats, on="FebruarySortedIndex", how="inner", validate="one_to_one")
    if len(data) != len(pred) or (data["TrueLabel"] != data["CategoryLabel"]).any():
        raise SystemExit("Category file does not line up with the predictions file.")

    y, p = data["TrueLabel"].to_numpy(), data["Prediction"].to_numpy()
    strata = sc.unsw_strata(y, data["AttackCategory"], data["Service"])
    rates = sc.stratum_rates(strata, y, p)
    pi0 = float(y.mean())
    table = sc.scenario_table(sc.standard_scenarios(rates, pi0), rates, pi0)

    recall = float(p[y == 1].mean())
    rule = lb.PoolingRule(n_min=lb.n_min_for_recall(recall))
    label_rows = []
    for availability in (1.0, 0.5, 0.2):
        mask = lb.label_mask(len(y), availability, seed=LABEL_SEED)
        cohorts = lb.pool_cohorts(lb.cohort_counts(y, p, mask, WINDOW_SIZE), rule, delay=0)
        label_rows.append(
            {
                "availability": availability,
                "windows": int(cohorts["span"].sum()),
                "cohorts": len(cohorts),
                "pooled_cohorts": int((cohorts["span"] > 1).sum()),
                "ineligible_cohorts": int((~cohorts["eligible"]).sum()),
            }
        )
    label_table = pd.DataFrame(label_rows)

    OUT.mkdir(parents=True, exist_ok=True)
    rates.to_csv(OUT / "feb_rf_validation_strata.csv", lineterminator="\n")
    table.to_csv(OUT / "feb_rf_validation_scenarios.csv", index=False, lineterminator="\n")
    label_table.to_csv(OUT / "feb_rf_validation_labels.csv", index=False, lineterminator="\n")

    cols = [
        "scenario",
        "intended",
        "label",
        "cal_f1_before",
        "cal_f1_after",
        "recall_after",
        "fpr_after",
        "mix_distance",
        "usable",
        "note",
    ]
    lines = [
        "# Scenario check: February validation, Random Forest",
        "",
        "Generated by `scripts/check_scenarios.py` (design spec D3, D4, D7, D8). "
        f"Reference attack share for calibrated F1: {pi0:.4f}. "
        f"Validation recall {recall:.4f}, so n_min = {rule.n_min} labelled attacks.",
        "",
        "## Scenarios",
        "",
        "| " + " | ".join(cols) + " |",
        "|" + "---|" * len(cols),
    ]
    for row in table[cols].itertuples(index=False):
        cells = [f"{v:.4f}" if isinstance(v, float) else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    lines += [
        "",
        "## Label cohorts (delay 0)",
        "",
        "| availability | windows | cohorts | pooled cohorts | ineligible cohorts |",
        "|---:|---:|---:|---:|---:|",
    ]
    for r in label_table.itertuples(index=False):
        lines.append(
            f"| {r.availability:.0%} | {r.windows} | {r.cohorts} | {r.pooled_cohorts} "
            f"| {r.ineligible_cohorts} |"
        )
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print("\nStrata with at least", sc.MIN_STRATUM_RECORDS, "records:")
    print(rates[rates["records"] >= sc.MIN_STRATUM_RECORDS].round(4).to_string())


if __name__ == "__main__":
    main()
