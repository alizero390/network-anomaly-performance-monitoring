"""Label-bias study for Paper 2: labelling policies, audit sampling, wrong weights (D17).

Usage (repository root, virtual environment active):

    python scripts/run_label_bias.py --partition validation     # about 10-20 minutes
    python scripts/run_label_bias.py --partition test           # needs the raw files

Validation needs only results/validation_predictions.csv and
results/validation_categories.csv (with Service, Proto, State). Test reads the raw files
for the strata and uses results/strategies/test/test_predictions.csv when present
(otherwise the saved model). Nothing is calibrated: references, n_min and the alarm rule
come from the frozen configs/strategies.toml, and the grid is fixed in
src/nadmon/label_bias.py.

Outputs in results/label_bias/<partition>/: stream_results.csv.gz, summary.csv,
policy_table.csv, summary.md, run.json
"""

from __future__ import annotations

import argparse
import json
import time
from dataclasses import replace

import joblib
import numpy as np
import pandas as pd

from nadmon import evaluation as ev
from nadmon import experiment as ex
from nadmon import february, frozen
from nadmon import label_bias as lbs
from nadmon import scenarios as sc
from nadmon.config import PROJECT_DIR, load_paths
from nadmon.provenance import run_metadata

RESULTS = PROJECT_DIR / "results"
CONFIG = PROJECT_DIR / "configs" / "strategies.toml"
STRATEGIES = ("B_F1", "B", "B_ipw", "B_ipw_eff")


def load_partition(which: str) -> ex.Partition:
    if which == "validation":
        pred = pd.read_csv(RESULTS / "validation_predictions.csv")
        cats = pd.read_csv(RESULTS / "validation_categories.csv", keep_default_na=False)
        if not {"Service", "Proto", "State"} <= set(cats.columns):
            raise SystemExit("Re-run scripts/export_validation_categories.py (needs Proto, State).")
        data = pred.merge(cats, on="FebruarySortedIndex", how="inner", validate="one_to_one")
        if len(data) != len(pred):
            raise SystemExit("Category file does not line up with the predictions file.")
        y = data["TrueLabel"].to_numpy(dtype=int)
        strata = sc.unsw_strata(
            y, data["AttackCategory"], data["Service"], data["Proto"], data["State"]
        )
        return ex.Partition(y, data["Prediction"].to_numpy(dtype=int), strata)

    paths = load_paths()
    X, y, category = february.load_frames(paths, "test")
    saved = RESULTS / "strategies" / "test" / "test_predictions.csv"
    if saved.is_file():
        pred = pd.read_csv(saved)
        if len(pred) != len(y) or (pred["TrueLabel"].to_numpy() != y).any():
            raise SystemExit("test_predictions.csv does not line up with the raw data.")
        p = pred["Prediction"].to_numpy(dtype=int)
    else:
        p = joblib.load(paths.models_dir / "random_forest_baseline.joblib").predict(X).astype(int)
    part = february.partition(X, y, category, p)
    return ex.Partition(part.y, part.p, part.strata)  # Strategy A is not part of this study


def policy_table(results: pd.DataFrame) -> pd.DataFrame:
    """One row per condition and strategy: harmless false alerts, harmful detection, delay."""
    rows = []
    for (cond, strat), g in results.groupby(["condition", "strategy"], sort=False):
        harmless = g[~g["harmful"]]
        harmful = g[g["harmful"]]
        rows.append(
            {
                "condition": cond,
                **lbs.parse_condition(cond),
                "strategy": strat,
                "false_alert_rate_stable_or_harmless": float(harmless["any_false_alert"].mean()),
                "detection_rate_harmful": float(harmful["detected"].mean()),
                "false_alert_rate_harmful_streams": float(harmful["any_false_alert"].mean()),
                "median_delay": float(harmful["detection_delay"].median()),
            }
        )
    return pd.DataFrame(rows)


def write_markdown(table: pd.DataFrame, which: str, info: dict, path) -> None:
    def pct(v):
        return "–" if pd.isna(v) else f"{v:.0%}"

    lines = [
        f"# Label-bias study (Paper 2): February {which}",
        "",
        "Generated by `scripts/run_label_bias.py`; grid fixed in `src/nadmon/label_bias.py` "
        "(D17). Label delay 5 windows. Per condition: false-alert rate on stable and "
        "harmless streams (S0, H1), detection rate and median delay on harmful streams "
        f"(X1, X2 and their `_rare` variants). {info['streams']} streams per scenario.",
        "",
        "| Condition | Weights | Strategy | False alerts (stable, harmless) | "
        "Detection (harmful) | Median delay |",
        "|---|---|---|---:|---:|---:|",
    ]
    for r in table.itertuples(index=False):
        delay = "–" if pd.isna(r.median_delay) else f"{r.median_delay:g}"
        lines.append(
            f"| {r.condition} | {r.weights} | {r.strategy} | "
            f"{pct(r.false_alert_rate_stable_or_harmless)} | {pct(r.detection_rate_harmful)} "
            f"| {delay} |"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--partition", choices=["validation", "test"], required=True)
    parser.add_argument("--streams", type=int, default=200)
    args = parser.parse_args()
    start = time.time()

    cfg = frozen.read_config(CONFIG)
    cal = frozen.calibration_from_config(cfg)
    settings = replace(frozen.settings_from_config(cfg), n_streams=args.streams, ipw_effective=True)
    out = RESULTS / "label_bias" / args.partition
    out.mkdir(parents=True, exist_ok=True)

    print(f"1. Loading the {args.partition} partition ...")
    part = load_partition(args.partition)
    print(f"   {len(part.y):,} records, attack share {part.y.mean():.3f}")

    print("2. Scenarios ...")
    rates = sc.stratum_rates(part.strata, part.y, part.p)
    base = sc.standard_scenarios(rates, cal.pi0)
    ok = set(sc.scenario_table(base, rates, cal.pi0).query("usable")["scenario"])
    candidates = base + sc.harder_variants([s for s in base if s.name in ok])
    table = sc.scenario_table(candidates, rates, cal.pi0)
    usable = set(table.loc[table["usable"], "scenario"])
    scenarios = [s for s in candidates if s.name in usable and s.name in lbs.SCENARIOS]
    missing = sorted(set(lbs.SCENARIOS) - {s.name for s in scenarios})
    print("   using:", ", ".join(s.name for s in scenarios))
    if missing:
        print("   not usable on this partition:", ", ".join(missing))

    conditions = lbs.policy_conditions()
    print(
        f"3. Grid: {len(conditions)} label conditions x {len(scenarios)} scenarios x "
        f"{settings.n_streams} streams ..."
    )
    results = ex.run_grid(part, scenarios, cal, settings, None, conditions=conditions)
    results.to_csv(out / "stream_results.csv.gz", index=False, lineterminator="\n")
    summary = ev.summarise(results, ["scenario", "condition", "strategy"])
    summary.to_csv(out / "summary.csv", index=False, lineterminator="\n")
    ptable = policy_table(results)
    ptable.to_csv(out / "policy_table.csv", index=False, lineterminator="\n")

    info = {
        "partition": args.partition,
        "streams": settings.n_streams,
        "conditions": len(conditions),
        "scenarios": [s.name for s in scenarios],
        "config_sha256": frozen.config_hash(CONFIG),
        "minutes": round((time.time() - start) / 60, 1),
        **run_metadata(),
    }
    (out / "run.json").write_text(json.dumps(info, indent=2, default=str) + "\n", encoding="utf-8")
    write_markdown(ptable, args.partition, info, out / "summary.md")

    show = ptable[ptable["weights"] == "correct"].pivot_table(
        index="condition",
        columns="strategy",
        values=["false_alert_rate_stable_or_harmless", "detection_rate_harmful"],
        sort=False,
    )
    np.set_printoptions(linewidth=200)
    pd.set_option("display.width", 220)
    print("\nFalse alerts on stable/harmless streams and detection of harmful ones:")
    print(show.round(3).to_string())
    wrong = ptable[ptable["weights"] != "correct"]
    print("\nWrong weights (B_ipw and B_ipw_eff):")
    print(
        wrong[wrong["strategy"].isin(["B_ipw", "B_ipw_eff"])][
            [
                "condition",
                "strategy",
                "false_alert_rate_stable_or_harmless",
                "detection_rate_harmful",
                "median_delay",
            ]
        ]
        .round(3)
        .to_string(index=False)
    )
    print(f"\nDone in {info['minutes']} minutes. Outputs in {out}")


if __name__ == "__main__":
    main()
