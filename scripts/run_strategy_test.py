"""One-time evaluation of Strategies A-C on the February test partition (design spec D1).

Usage (repository root, virtual environment active, raw data available):

    python scripts/run_strategy_test.py --check-only           # guards only, seconds
    python scripts/run_strategy_test.py --confirm-committed    # the real run, about 2-3 hours

Nothing is calibrated here: every threshold comes from configs/strategies.toml, written
by the full validation run (scripts/run_strategy_experiment.py) and committed before
this script runs. The script refuses to run if

- the config comes from a quick run, or its values differ from
  results/strategies/validation/calibration.json;
- the config is not committed (checked with git when the git command is available;
  otherwise you confirm with --confirm-committed after committing in GitHub Desktop);
- results/strategies/test/ already holds a test run (the test partition is used once;
  --resume-identical repeats an interrupted run only if the config is byte-identical).

Steps: Strategy A reference from validation (same random half and sample as the
validation run); test predictions from the saved baseline model; scenarios rebuilt from
the test partition's own strata (ground truth only, nothing tuned); full grid; the
strategies on the real test windows in time order.

Outputs in results/strategies/test/: run.json, scenarios.csv, stream_results.csv.gz,
summary.csv, summary.md, paired_*.csv, natural_test.csv (test_predictions.csv is local
only and not committed).
"""

from __future__ import annotations

import argparse
import json
import time

import joblib
import numpy as np
import pandas as pd

from nadmon import evaluation as ev
from nadmon import experiment as ex
from nadmon import february, frozen
from nadmon import scenarios as sc
from nadmon import strategies as st
from nadmon.config import PROJECT_DIR, load_paths
from nadmon.provenance import run_metadata

RESULTS = PROJECT_DIR / "results"
CONFIG = PROJECT_DIR / "configs" / "strategies.toml"
VALIDATION_CALIBRATION = RESULTS / "strategies" / "validation" / "calibration.json"
OUT = RESULTS / "strategies" / "test"


def guards(args) -> dict:
    """Run every check; exit with a clear message if one fails. Returns the config."""
    if not CONFIG.is_file():
        raise SystemExit(f"{CONFIG} not found: run the full validation first.")
    cfg = frozen.read_config(CONFIG)
    problems = frozen.check_against_validation(cfg, VALIDATION_CALIBRATION)
    if problems:
        raise SystemExit("Config is not final:\n- " + "\n- ".join(problems))

    committed = frozen.committed_unchanged(CONFIG, PROJECT_DIR)
    if committed is False:
        raise SystemExit("configs/strategies.toml has uncommitted changes. Commit it first.")
    if committed is None and not args.confirm_committed and not args.check_only:
        raise SystemExit(
            "The git command is not available, so the commit cannot be checked here.\n"
            "Commit configs/strategies.toml in GitHub Desktop, then run again with "
            "--confirm-committed."
        )

    run_json = OUT / "run.json"
    if run_json.is_file():
        previous = json.loads(run_json.read_text(encoding="utf-8"))
        same = previous.get("config_sha256") == frozen.config_hash(CONFIG)
        if not args.resume_identical:
            raise SystemExit(
                "A test run already exists in results/strategies/test/. The test partition "
                "is used once. To repeat an interrupted run with the identical config, "
                "use --resume-identical."
            )
        if not same:
            raise SystemExit("The config changed since the earlier test run: not allowed.")
    return cfg


def test_metrics(y: np.ndarray, p: np.ndarray, pi0: float) -> dict:
    tp = int(((y == 1) & (p == 1)).sum())
    fp = int(((y == 0) & (p == 1)).sum())
    fn = int(((y == 1) & (p == 0)).sum())
    tn = int(((y == 0) & (p == 0)).sum())
    recall = tp / (tp + fn) if tp + fn else float("nan")
    fpr = fp / (fp + tn) if fp + tn else float("nan")
    return {
        "records": int(len(y)),
        "attack_share": float(y.mean()),
        "recall": recall,
        "fpr": fpr,
        "f1": 2 * tp / (2 * tp + fp + fn),
        "f1_calibrated_at_validation_share": float(st.calibrated_f1(recall, fpr, pi0)),
    }


def write_summary(summary: pd.DataFrame, natural: pd.DataFrame, info: dict) -> None:
    def pct(v):
        return "–" if pd.isna(v) else f"{v:.0%}"

    m = info["test_metrics"]
    lines = [
        "# Strategy comparison: February test partition (one-time run)",
        "",
        "Generated by `scripts/run_strategy_test.py` with the frozen settings in "
        f"`configs/strategies.toml` (SHA-256 {info['config_sha256'][:12]}...). Nothing was "
        "calibrated on test data.",
        "",
        f"Test partition: {m['records']:,} records, attack share {m['attack_share']:.3f}, "
        f"recall {m['recall']:.4f}, FPR {m['fpr']:.4f}, F1 {m['f1']:.4f}, calibrated F1 "
        f"{m['f1_calibrated_at_validation_share']:.4f} (validation reference "
        f"{info['reference_f1_calibrated']:.4f}).",
        "",
        "Scenarios not usable on test (ground truth not clean): "
        + (", ".join(info["unusable_scenarios"]) or "none"),
        "",
        "| Scenario | Condition | Strategy | Streams | Event recall | False-alert rate | "
        "Median delay |",
        "|---|---|---|---:|---:|---:|---:|",
    ]
    for r in summary.itertuples(index=False):
        delay = "–" if pd.isna(r.median_delay) else f"{r.median_delay:g}"
        lines.append(
            f"| {r.scenario} | {r.condition} | {r.strategy} | {r.streams} | "
            f"{pct(r.event_recall)} | {pct(r.false_alert_rate)} | {delay} |"
        )
    lines += [
        "",
        "## Real test windows in time order",
        "",
        "| Strategy | Condition | Windows | Alarms | Alarm windows |",
        "|---|---|---:|---:|---|",
    ]
    for r in natural.itertuples(index=False):
        lines.append(
            f"| {r.strategy} | {r.condition} | {r.windows} | {r.alarms} | {r.alarm_windows} |"
        )
    (OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check-only", action="store_true", help="run the guards and stop")
    parser.add_argument("--confirm-committed", action="store_true")
    parser.add_argument("--resume-identical", action="store_true")
    parser.add_argument("--streams", type=int, default=None, help="default: 200")
    args = parser.parse_args()

    cfg = guards(args)
    cal = frozen.calibration_from_config(cfg)
    settings = frozen.settings_from_config(cfg)
    if args.streams:
        settings = ex.Settings(**{**settings.__dict__, "n_streams": args.streams})
    print("Frozen settings OK:")
    print(
        f"   q = {cal.q:.3f}, q_natural = {cal.q_natural}, n_min = {cal.n_min}, "
        f"L = {cal.periods}, reference calibrated F1 = {cal.reference_f1_calibrated:.4f}"
    )
    if args.check_only:
        print("Check only: stopping before any data is loaded.")
        return

    start = time.time()
    OUT.mkdir(parents=True, exist_ok=True)
    paths = load_paths()

    print("1. Strategy A reference from validation (same half and sample as before) ...")
    X_val, y_val, cat_val = february.load_frames(paths, "validation")
    pred_val = pd.read_csv(RESULTS / "validation_predictions.csv")["Prediction"].to_numpy()
    val = february.partition(X_val, y_val, cat_val, pred_val)
    ref_idx, _ = ex.split_validation(len(val.y), settings.seed)
    ref = ex.a_reference(val.subset(ref_idx), settings)
    del X_val, val

    print("2. Test partition and predictions from the saved model ...")
    X_test, y_test, cat_test = february.load_frames(paths, "test")
    model = joblib.load(paths.models_dir / "random_forest_baseline.joblib")
    pred_test = model.predict(X_test).astype(int)
    pd.DataFrame({"TrueLabel": y_test, "Prediction": pred_test}).to_csv(
        OUT / "test_predictions.csv", index=False, lineterminator="\n"
    )
    test = february.partition(X_test, y_test, cat_test, pred_test)
    metrics = test_metrics(test.y, test.p, cal.pi0)
    print(
        f"   {metrics['records']:,} records; attack share {metrics['attack_share']:.3f}; "
        f"recall {metrics['recall']:.4f}; FPR {metrics['fpr']:.4f}; F1 {metrics['f1']:.4f}"
    )

    print("3. Scenarios from the test partition's strata ...")
    rates = sc.stratum_rates(test.strata, test.y, test.p)
    base = sc.standard_scenarios(rates, cal.pi0)
    base_ok = set(sc.scenario_table(base, rates, cal.pi0).query("usable")["scenario"])
    all_scen = base + sc.harder_variants([s for s in base if s.name in base_ok])
    table = sc.scenario_table(all_scen, rates, cal.pi0)
    table.to_csv(OUT / "scenarios.csv", index=False, lineterminator="\n")
    usable = set(table.loc[table["usable"], "scenario"])
    scenarios = [s for s in all_scen if s.name in usable]
    expected = {
        "S0_stable",
        "H1_fewer_attacks",
        "H2_benign_mix",
        "H3_easy_attack_mix",
        "X1_hard_attack_mix",
        "X2_false_positive_burst",
    }
    unusable = sorted(expected - usable)
    print(
        table[["scenario", "intended", "label", "cal_f1_change", "usable"]].to_string(index=False)
    )

    print("4. Grid ...")
    results = ex.run_grid(test, scenarios, cal, settings, ref)
    results.to_csv(OUT / "stream_results.csv.gz", index=False, lineterminator="\n")
    summary = ev.summarise(results, ["scenario", "condition", "strategy"])
    summary.to_csv(OUT / "summary.csv", index=False, lineterminator="\n")
    for a, b in (("B", "B_F1"), ("C_active", "B"), ("B_ipw", "B")):
        ev.paired_comparison(results, a, b).to_csv(
            OUT / f"paired_{a}_vs_{b}.csv", index=False, lineterminator="\n"
        )

    print("5. Real test windows in time order ...")
    natural = ex.run_natural(test, cal, settings, ref, seed=settings.seed)
    natural.to_csv(OUT / "natural_test.csv", index=False, lineterminator="\n")

    info = {
        "config_sha256": frozen.config_hash(CONFIG),
        "reference_f1_calibrated": cal.reference_f1_calibrated,
        "test_metrics": metrics,
        "unusable_scenarios": unusable,
        "streams_per_scenario": settings.n_streams,
        "minutes": round((time.time() - start) / 60, 1),
        **run_metadata(),
    }
    (OUT / "run.json").write_text(json.dumps(info, indent=2, default=str) + "\n", encoding="utf-8")
    write_summary(summary, natural, info)

    overview = ev.summarise(
        results[~results["condition"].str.contains("alert_first")], ["scenario", "strategy"]
    )
    cols = ["scenario", "strategy", "event_recall", "false_alert_rate", "median_delay"]
    print("\nOverview (random-label conditions pooled):")
    print(overview[cols].round(3).to_string(index=False))
    af = ev.summarise(
        results[results["condition"].str.contains("alert_first")], ["scenario", "strategy"]
    )
    print("\nAlert-first labels:")
    print(af[af["strategy"].isin(["B", "B_F1", "B_ipw"])][cols].round(3).to_string(index=False))
    print("\nTime-ordered test windows:")
    print(natural[["strategy", "condition", "alarms", "alarm_windows"]].to_string(index=False))
    print(f"\nDone in {info['minutes']} minutes. Outputs in {OUT}")


if __name__ == "__main__":
    main()
